#![no_main]

use gradus_encryption::{
    BlobBinding, decode_encrypted_blob, decode_personal_vault_key_from_storage, decrypt_blob,
};
use libfuzzer_sys::fuzz_target;

const VECTOR_KEY: [u8; 57] = [
    b'G', b'R', b'D', b'V', b'K', b'E', b'Y', 0, 1, 0xA1, 0xA1, 0xA1, 0xA1, 0xA1, 0xA1, 0xA1, 0xA1,
    0xA1, 0xA1, 0xA1, 0xA1, 0xA1, 0xA1, 0xA1, 0xA1, 0xA1, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2,
    0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2,
    0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2, 0xB2,
];

fn binding() -> BlobBinding {
    BlobBinding {
        data_space_id: [
            0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D,
            0x0E, 0x0F,
        ],
        resource_type_id: [
            0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D,
            0x1E, 0x1F,
        ],
        resource_id: [
            0x80, 0x81, 0x82, 0x83, 0x84, 0x85, 0x86, 0x87, 0x88, 0x89, 0x8A, 0x8B, 0x8C, 0x8D,
            0x8E, 0x8F,
        ],
        revision: 0x0102_0304_0506_0708,
    }
}

fuzz_target!(|input: &[u8]| {
    let Ok(blob) = decode_encrypted_blob(input) else {
        return;
    };
    let key = decode_personal_vault_key_from_storage(&VECTOR_KEY).expect("fixed key is valid");
    let _ = decrypt_blob(&key, &blob, &binding());
});
